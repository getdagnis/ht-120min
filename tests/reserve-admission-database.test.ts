import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFile, execFileSync } from 'node:child_process';
import test from 'node:test';
const socket = process.env.HT120_TEST_POSTGRES_SOCKET;
const enabled = Boolean(socket?.startsWith('/private/tmp/ht120-calendar-pg.') || socket?.startsWith('/tmp/ht120-calendar-pg.'));
const sql = (input: string) => execFileSync('psql', ['-h', socket!, '-p', '55442', '-U', 'postgres', '-v', 'ON_ERROR_STOP=1', '-A', '-t', '-q'], { input, encoding: 'utf8' });
const id = (n: number) => `10000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
const quoted = (data: unknown) => `'${JSON.stringify(data).replaceAll("'", "''")}'::jsonb`;

test('reserve admission appends slots atomically, preserves existing results and is idempotent', { skip: !enabled }, async () => {
  sql('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
  sql(readFileSync(new URL('./fixtures/calendar-schedule-schema.sql', import.meta.url), 'utf8'));
  sql(`ALTER TABLE tournaments ADD max_teams integer, ADD is_test boolean, ADD is_archived boolean, ADD registration_type text;
    ALTER TABLE teams ADD reserve_joined_at timestamptz;
    ALTER TABLE matches ADD reserve_team_id uuid, ADD reserve_replaces_team_id uuid;
    CREATE TABLE profiles(hattrick_user_id bigint,teams_json jsonb);
    ALTER TABLE tournament_season_slot_assignments ADD assigned_at timestamptz DEFAULT now();
    ALTER TABLE tournament_season_slots ADD CHECK(box_size%2=0 AND slot_index<=box_size);`);
  sql(readFileSync(new URL('../migrations/107_calendar_first_generated_schedules.sql', import.meta.url), 'utf8'));
  sql(readFileSync(new URL('../migrations/108_validated_reserve_admission.sql', import.meta.url), 'utf8'));
  sql(readFileSync(new URL('../migrations/109_remove_unused_tournament_reserve.sql', import.meta.url), 'utf8'));
  const pairs = [{ home_team_id: id(5), away_team_id: id(6), scheduled_for: '2030-03-19T18:25:00Z' }];
  const admit = (request = id(30), teamIds = [id(5), id(6)], raise = true, incoming = pairs) => `SELECT admit_length_schedule_reserves('${id(10)}',1,'${id(20)}','${request}',ARRAY[${teamIds.map(x => `'${x}'::uuid`).join(',')}],${quoted(incoming)},${raise});`;
  sql(`INSERT INTO tournaments(id,season,league_category,status,schedule_mode,max_teams) VALUES('${id(10)}',1,'male','active','length',4);
    INSERT INTO tournament_seasons(id,tournament_id,season_number,status) VALUES('${id(11)}','${id(10)}',1,'ongoing');
    INSERT INTO rounds(id,tournament_id,season_number,round_number,phase,phase_status,reserved_slot_kind) VALUES('${id(20)}','${id(10)}',1,1,'regular','materialized','midweek_friendly');
    ${Array.from({ length: 8 }, (_, i) => `INSERT INTO teams(id,tournament_id,name,ht_team_id,active,reserve_active,power_rating) VALUES('${id(i + 1)}','${id(10)}','Team ${i + 1}',${i + 1},${i < 4},${i >= 4},${1000 + i});`).join('\n')}
    ${Array.from({ length: 4 }, (_, i) => `INSERT INTO tournament_season_slots(tournament_season_id,slot_index,box_size,current_team_id) VALUES('${id(11)}',${i + 1},4,'${id(i + 1)}');`).join('\n')}
    INSERT INTO matches(id,round_id,home_team_id,away_team_id,status,completed,schedule_resolution) VALUES('${id(40)}','${id(20)}','${id(1)}','${id(2)}','finished',true,'played'),('${id(41)}','${id(20)}','${id(3)}','${id(4)}','ongoing',false,'pending');`);
  const oldMatches = sql(`SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM matches m;`);
  sql(`UPDATE matches SET reserve_team_id='${id(5)}' WHERE id='${id(40)}';`);
  assert.throws(() => sql(admit()), /slot or fixture/);
  sql('UPDATE matches SET reserve_team_id=NULL;');
  assert.throws(() => sql(admit(id(30), [id(5), id(6)], false)), /Confirm increasing/);
  assert.equal(sql('SELECT count(*) FROM tournament_season_slots;').trim(), '4');
  await Promise.all([1, 2].map(() => new Promise<string>((resolve, reject) => {
    const child = execFile('psql', ['-h', socket!, '-p', '55442', '-U', 'postgres', '-v', 'ON_ERROR_STOP=1', '-A', '-t', '-q'], { encoding: 'utf8' }, (error, stdout) => error ? reject(error) : resolve(stdout));
    child.stdin!.end(admit());
  })));
  assert.match(sql(admit()), /already_applied.*true/);
  assert.equal(sql('SELECT count(*) FROM matches;').trim(), '3');
  assert.equal(sql('SELECT count(*) FROM tournament_season_slots;').trim(), '6');
  assert.equal(sql(`SELECT max_teams FROM tournaments;`).trim(), '6');
  assert.equal(sql(`SELECT jsonb_agg(to_jsonb(m) ORDER BY id) FROM matches m WHERE id IN ('${id(40)}','${id(41)}');`), oldMatches);
  assert.throws(() => sql(admit(id(31))), /reserve list changed/);
  assert.throws(() => sql(admit(id(30), [id(7), id(8)])), /original selection/);
  assert.throws(() => sql(admit(id(32), [id(7), id(8)], true, [{ ...pairs[0]!, away_team_id: id(7) }])), /Invalid or duplicate/);
  assert.equal(sql(`SELECT count(*) FROM teams WHERE reserve_active=true;`).trim(), '2');
  assert.equal(sql(`SELECT get_length_reserve_admission_receipt('${id(10)}','${id(20)}','${id(30)}',ARRAY['${id(6)}'::uuid,'${id(5)}'::uuid]);`).includes('already_applied'), true);
  sql(`INSERT INTO rounds(id,tournament_id,season_number,round_number,phase,phase_status,reserved_slot_kind) VALUES('${id(21)}','${id(10)}',1,2,'regular','pending','midweek_friendly');
    UPDATE matches SET completed=true,status='finished';
    SELECT apply_length_round_transition('${id(10)}',1,'${id(20)}','${id(21)}',${quoted([{ home_team_id: id(1), away_team_id: id(5) }, { home_team_id: id(2), away_team_id: id(6) }, { home_team_id: id(3), away_team_id: id(4) }])},NULL);`);
  assert.equal(sql(`SELECT count(*) FROM matches WHERE round_id='${id(21)}';`).trim(), '3');
  assert.equal(sql(`SELECT count(*) FROM matches WHERE round_id='${id(20)}' AND (home_team_id IN ('${id(5)}','${id(6)}') OR away_team_id IN ('${id(5)}','${id(6)}'));`).trim(), '1');
  sql(`INSERT INTO profiles VALUES(1,${quoted([{ teamId: 876 }])}),(2,${quoted(JSON.stringify([{ teamId: 987 }]))}),(3,'"invalid-json"');`);
  assert.equal(sql('SELECT * FROM find_known_team_managers(876);').trim(), '1');
  assert.equal(sql('SELECT * FROM find_known_team_managers(987);').trim(), '2');
  sql('GRANT USAGE ON SCHEMA public TO authenticated,anon;');
  assert.throws(() => sql(`SET ROLE authenticated; ${admit()}`), /permission denied/);
  sql(`UPDATE rounds SET phase='postseason';`);
  assert.throws(() => sql(admit(id(32), [id(7), id(8)], true, [{ home_team_id: id(7), away_team_id: id(8), scheduled_for: '2030-03-19T18:25:00Z' }])), /before playoffs/);
  const remove = (team = id(7), tournament = id(10)) => `SELECT remove_unused_tournament_reserve('${tournament}','${team}');`;
  assert.throws(() => sql(remove(id(5))), /Only unused reserve/);
  sql(`UPDATE matches SET reserve_team_id='${id(7)}' WHERE id='${id(40)}';`);
  assert.throws(() => sql(remove()), /fixtures or season history/);
  sql('UPDATE matches SET reserve_team_id=NULL;');
  sql(`CREATE TABLE reserve_history(team_id uuid REFERENCES teams(id) ON DELETE CASCADE);
    INSERT INTO reserve_history VALUES('${id(7)}');`);
  assert.throws(() => sql(remove()), /existing history/);
  assert.equal(sql('SELECT count(*) FROM reserve_history;').trim(), '1');
  sql('DELETE FROM reserve_history;');
  assert.throws(() => sql(`SET ROLE authenticated; ${remove()}`), /permission denied/);
  sql(`INSERT INTO tournaments(id) VALUES('${id(12)}');`);
  sql(remove(id(7), id(12)));
  assert.equal(sql(`SELECT count(*) FROM teams WHERE id='${id(7)}';`).trim(), '1');
  sql(remove());
  sql(remove());
  assert.equal(sql(`SELECT count(*) FROM teams WHERE id IN ('${id(7)}','${id(8)}');`).trim(), '1');
});
